export const UI_STRINGS: Record<UiLanguage, Record<UiStringKey, string>> = { en, fa };

/** `{placeholder}` interpolation, e.g. t("questionOf", { current: 1, total: 10 }). */
export function translate(language: UiLanguage, key: UiStringKey, vars?: Record<string, string | number>): string {
  const template = UI_STRINGS[language][key] ?? UI_STRINGS.en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}
